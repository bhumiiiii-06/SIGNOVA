export function getConceptSign(word) {
  if (!word) return null;
  const cleanWord = String(word).trim().toUpperCase();

  // Direct match
  if (ISL_CONCEPT_SIGNS[cleanWord]) {
    return ISL_CONCEPT_SIGNS[cleanWord];
  }

  // Alias / synonym matching
  const aliases = {
    RAINFALL: "RAIN",
    PRECIPITATION: "RAIN",
    STORM: "CYCLONE",
    FLOODING: "FLOOD",
    LANDSLIDE: "EARTHQUAKE",
    TSUNAMI: "FLOOD",
    SCHOOLS: "SCHOOL",
    COLLEGE: "SCHOOL",
    STUDENT: "SCHOOL",
    TEACHER: "SCHOOL",
    DOCTORS: "DOCTOR",
    HOSPITALS: "HOSPITAL",
    MEDICINE: "HOSPITAL",
    RESCUE: "HELP",
    ALERT: "WARNING",
    CLOSED: "CLOSE",
    CLOSES: "CLOSE",
    STOP: "CLOSE",
    TRAINS: "TRAIN",
    BUSES: "BUS",
  };

  const aliasMatch = aliases[cleanWord];
  if (aliasMatch && ISL_CONCEPT_SIGNS[aliasMatch]) {
    return {
      ...ISL_CONCEPT_SIGNS[aliasMatch],
      originalWord: cleanWord,
    };
  }

  return null;
}

